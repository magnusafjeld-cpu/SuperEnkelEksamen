<p>The most obvious risk is <b>free riding</b>: a member enjoys the benefits of membership without observing the coalition's rules. Schoenmaker &amp; Schramade therefore apply <b>Ostrom's (1990)</b> principles for governing common resources: clearly defined boundaries (coverage of the sector), membership rules (how ambitious, SF 1.0 to 3.0, see kj1), collective-choice arrangements, monitoring, sanctions and rewards and a conflict-resolution mechanism.</p>

